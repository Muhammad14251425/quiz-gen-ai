#!/usr/bin/env node
/**
 * Generates src/features/map/geo/countries.ts (offline base map) from Natural
 * Earth via world-atlas (public domain). Pakistan uses the 1:10m dataset,
 * neighbours 1:50m. Points are rounded and thinned to keep the bundle small.
 * Usage: node scripts/gen-map-data.js
 */
const fs = require('fs');
const path = require('path');
const { feature } = require('topojson-client');

const COUNTRIES = [
  { id: '586', name: 'Pakistan', res: '10m', minStep: 0.02 },
  { id: '356', name: 'India', res: '50m', minStep: 0.08 },
  { id: '004', name: 'Afghanistan', res: '50m', minStep: 0.08 },
  { id: '364', name: 'Iran', res: '50m', minStep: 0.08 },
  { id: '156', name: 'China', res: '50m', minStep: 0.08 },
  { id: '512', name: 'Oman', res: '50m', minStep: 0.08 },
  { id: '784', name: 'United Arab Emirates', res: '50m', minStep: 0.08 },
  { id: '795', name: 'Turkmenistan', res: '50m', minStep: 0.08 },
  { id: '762', name: 'Tajikistan', res: '50m', minStep: 0.08 },
];

const atlas = (res) => require(`world-atlas/countries-${res}.json`);
const round = (n) => Math.round(n * 1000) / 1000;

function thin(ring, minStep) {
  const out = [];
  for (const [lng, lat] of ring) {
    const prev = out[out.length - 1];
    if (!prev || Math.abs(prev[0] - lng) + Math.abs(prev[1] - lat) >= minStep) out.push([round(lng), round(lat)]);
  }
  return out.length >= 4 ? out : null;
}

const result = COUNTRIES.map(({ id, name, res, minStep }) => {
  const topo = atlas(res);
  const f = feature(topo, topo.objects.countries).features.find((x) => x.id === id);
  if (!f) throw new Error(`Country ${id} not found`);
  const polys = f.geometry.type === 'Polygon' ? [f.geometry.coordinates] : f.geometry.coordinates;
  // Outer rings only; holes are irrelevant at this scale.
  const rings = polys.map((p) => thin(p[0], minStep)).filter(Boolean);
  return { name, home: id === '586', rings };
});

const points = result.reduce((n, c) => n + c.rings.reduce((m, r) => m + r.length, 0), 0);
const out = `// Generated by scripts/gen-map-data.js from Natural Earth (public domain) — do not edit by hand.
/** Country outlines as rings of [longitude, latitude]. */
export interface CountryShape {
  name: string;
  /** The country the app is built for; drawn emphasized. */
  home: boolean;
  rings: [number, number][][];
}

export const COUNTRIES: CountryShape[] = ${JSON.stringify(result)};
`;
fs.writeFileSync(path.join(__dirname, '..', 'src', 'features', 'map', 'geo', 'countries.ts'), out);
console.log(`Wrote ${result.length} countries, ${points} points, ${(out.length / 1024).toFixed(0)} KB`);
