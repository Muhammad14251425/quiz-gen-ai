#!/usr/bin/env node
/**
 * Generates src/features/debug/sampleTexts.ts from the real-receipt OCR fixtures
 * so the dev debug screen can simulate imports on emulators/web without OCR.
 * Usage: node scripts/gen-sample-texts.js
 */
const fs = require('fs');
const path = require('path');

const dir = path.join(__dirname, '..', 'src', 'parser', '__fixtures__');
const files = fs
  .readdirSync(dir)
  .filter((f) => /^real_\d+.*\.txt$/.test(f))
  .sort();
const entries = files.map(
  (f) => `  ${JSON.stringify(f.replace(/\.txt$/, ''))}: ${JSON.stringify(fs.readFileSync(path.join(dir, f), 'utf8'))},`,
);
const out = `// Generated by scripts/gen-sample-texts.js — do not edit by hand.
/** OCR text of the real sample receipts, keyed by fixture name (matches assets/samples/<name>.jpg). */
export const SAMPLE_TEXTS: Record<string, string> = {
${entries.join('\n')}
};
`;
fs.writeFileSync(path.join(__dirname, '..', 'src', 'features', 'debug', 'sampleTexts.ts'), out);
console.log(`Wrote ${files.length} sample texts`);
